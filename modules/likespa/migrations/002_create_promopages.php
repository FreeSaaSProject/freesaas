<?php
declare(strict_types=1);

/**
 * Landing / promo pages (oper base_promopages).
 */
return static function (PDO $pdo): void {
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_promopages (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            DESCR VARCHAR(255) NOT NULL DEFAULT '',
            CODE VARCHAR(10) NOT NULL DEFAULT '',
            SKIN VARCHAR(20) NOT NULL DEFAULT '',
            TPL VARCHAR(100) NOT NULL DEFAULT '',
            SHOWS INT UNSIGNED NOT NULL DEFAULT 0,
            META_TITLE VARCHAR(255) NOT NULL DEFAULT '',
            META_DESCR MEDIUMTEXT NULL,
            DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_UPDATE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_OPERATOR_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_OPERATOR_UPDATE INT UNSIGNED NOT NULL DEFAULT 0,
            ENABLED TINYINT UNSIGNED NOT NULL DEFAULT 1,
            MODULES MEDIUMTEXT NULL,
            CAN_USE_OLDCLIENTS TINYINT UNSIGNED NOT NULL DEFAULT 1,
            CAN_USE_CLUBERS TINYINT UNSIGNED NOT NULL DEFAULT 1,
            CAN_USE_NEWCLIENT TINYINT UNSIGNED NOT NULL DEFAULT 1,
            CAN_PAY_ONLINE_ONLY TINYINT UNSIGNED NOT NULL DEFAULT 1,
            CAN_PAY_OFFLINE_ONLY TINYINT UNSIGNED NOT NULL DEFAULT 1,
            CAN_USE_DCO TINYINT UNSIGNED NOT NULL DEFAULT 1,
            CAN_USE_BONUS TINYINT UNSIGNED NOT NULL DEFAULT 1,
            CAN_SCHEDULE TINYINT UNSIGNED NOT NULL DEFAULT 1,
            DT_EXPIRE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_USE_ONLY INT UNSIGNED NOT NULL DEFAULT 0,
            MINIMAL_SUMM_LIMIT INT UNSIGNED NOT NULL DEFAULT 0,
            TYPES MEDIUMTEXT NULL,
            PRICECOL TINYINT UNSIGNED NOT NULL DEFAULT 0,
            DISCOUNT INT UNSIGNED NOT NULL DEFAULT 0,
            GOOD_PRICES MEDIUMTEXT NULL,
            SPECIAL_MENU TINYINT UNSIGNED NOT NULL DEFAULT 0,
            ID_PARENT INT UNSIGNED NOT NULL DEFAULT 0,
            SYNONIMS MEDIUMTEXT NULL,
            COSM_LIMIT MEDIUMTEXT NULL,
            PHONE VARCHAR(16) NOT NULL DEFAULT '',
            THANKS_URL VARCHAR(255) NOT NULL DEFAULT '',
            CAN_USE_TODAY_ONLY TINYINT UNSIGNED NOT NULL DEFAULT 0,
            PRIMARY KEY (ID),
            KEY idx_code (CODE),
            KEY idx_parent (ID_PARENT),
            KEY idx_enabled (ENABLED)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );
};
