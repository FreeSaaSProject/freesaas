<?php
declare(strict_types=1);

/**
 * Receipt/writeoff acts + sticker lines. Shared with legacy oper.
 */
return static function (PDO $pdo): void {
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_acts2_in (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            ID_SUPPLIER INT UNSIGNED NOT NULL DEFAULT 0,
            ID_STOCK INT UNSIGNED NOT NULL DEFAULT 0,
            ID_USER_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_USER_SIGNED INT UNSIGNED NOT NULL DEFAULT 0,
            DESCR VARCHAR(255) NOT NULL DEFAULT '',
            LOG MEDIUMTEXT NOT NULL,
            DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            IS_STICKED TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            IS_STRANGE TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            IS_SIGNED TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            SUMM FLOAT UNSIGNED NOT NULL DEFAULT 0,
            PRIMARY KEY (ID),
            KEY idx_stock (ID_STOCK),
            KEY idx_dt (DT_CREATE)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );

    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_acts2_out (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            ID_EVENT INT UNSIGNED NOT NULL DEFAULT 0,
            ID_PROC INT UNSIGNED NOT NULL DEFAULT 0,
            ID_GOOD INT UNSIGNED NOT NULL DEFAULT 0,
            ID_STOCK INT UNSIGNED NOT NULL DEFAULT 0,
            ID_USER INT UNSIGNED NOT NULL DEFAULT 0,
            DESCR MEDIUMTEXT NOT NULL,
            DT INT NOT NULL DEFAULT 0,
            DEFAULT_WARNING MEDIUMTEXT NOT NULL,
            ID_USER_SIGNED INT UNSIGNED NOT NULL DEFAULT 0,
            DT_USER_SIGNED INT UNSIGNED NOT NULL DEFAULT 0,
            SUMM_DEFAULT FLOAT UNSIGNED NOT NULL DEFAULT 0,
            SUMM_REAL FLOAT NOT NULL DEFAULT 0,
            ID_COSM_CONNECTED INT UNSIGNED NOT NULL DEFAULT 0,
            ID_COSM_SIGNED INT UNSIGNED NOT NULL DEFAULT 0,
            DT_COSM_SIGNED INT UNSIGNED NOT NULL DEFAULT 0,
            IS_REVI TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            THEREIS_INCOME TINYINT UNSIGNED NOT NULL DEFAULT 0,
            IS_STRANGE TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            PRIMARY KEY (ID),
            KEY idx_stock (ID_STOCK),
            KEY idx_user_dt (ID_USER, DT)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );

    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_good_sticker_ins (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            ID_USER_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_ACT INT UNSIGNED NOT NULL DEFAULT 0,
            ID_GOOD INT UNSIGNED NOT NULL DEFAULT 0,
            ID_STOCK INT UNSIGNED NOT NULL DEFAULT 0,
            ID_SUPPLIER INT UNSIGNED NOT NULL DEFAULT 0,
            DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_EXPIRE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_REVISION INT UNSIGNED NOT NULL DEFAULT 0,
            DT_MOVEMENT INT UNSIGNED NOT NULL DEFAULT 0,
            DT_PRINT INT UNSIGNED NOT NULL DEFAULT 0,
            DT_REPRINT INT UNSIGNED NOT NULL DEFAULT 0,
            PIN VARCHAR(10) NOT NULL DEFAULT '',
            HASH VARCHAR(32) NOT NULL DEFAULT '',
            LOG MEDIUMTEXT NOT NULL,
            PRICE DOUBLE UNSIGNED NOT NULL DEFAULT 0,
            QTY INT UNSIGNED NOT NULL DEFAULT 1,
            QTYU_IN FLOAT UNSIGNED NOT NULL DEFAULT 0,
            QTYU_OUT FLOAT NOT NULL DEFAULT 0,
            QTY_QTYU_RATE FLOAT UNSIGNED NOT NULL DEFAULT 1,
            DESCR_STOCK VARCHAR(255) NOT NULL DEFAULT '',
            DESCR VARCHAR(255) NOT NULL DEFAULT '',
            IS_STRANGE MEDIUMTEXT NOT NULL,
            WEIGHT_START DOUBLE UNSIGNED NOT NULL DEFAULT 0,
            TOKEN VARCHAR(32) NOT NULL DEFAULT '',
            PRIMARY KEY (ID),
            KEY idx_act (ID_ACT),
            KEY idx_good (ID_GOOD),
            KEY idx_stock (ID_STOCK),
            KEY idx_hash (HASH)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );

    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_good_sticker_outs (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_USER INT UNSIGNED NOT NULL DEFAULT 0,
            ID_USER_AFTER INT UNSIGNED NOT NULL DEFAULT 0,
            ID_GOOD INT UNSIGNED NOT NULL DEFAULT 0,
            ID_STOCK INT UNSIGNED NOT NULL DEFAULT 0,
            ID_ACT INT UNSIGNED NOT NULL DEFAULT 0,
            ID_STICKER INT UNSIGNED NOT NULL DEFAULT 0,
            QTYU FLOAT NOT NULL DEFAULT 0,
            SUM FLOAT NOT NULL DEFAULT 0,
            DESCR VARCHAR(255) NOT NULL DEFAULT '',
            WEIGHT_BEFORE DOUBLE UNSIGNED NOT NULL DEFAULT 0,
            WEIGHT_AFTER DOUBLE NOT NULL DEFAULT 0,
            TOKEN VARCHAR(32) NOT NULL DEFAULT '',
            PRIMARY KEY (ID),
            KEY idx_sticker (ID_STICKER),
            KEY idx_act (ID_ACT),
            KEY idx_dt (DT_CREATE)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );
};
