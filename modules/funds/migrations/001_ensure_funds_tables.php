<?php
declare(strict_types=1);

return static function (PDO $pdo): void {
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_funds (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            PID INT UNSIGNED NOT NULL DEFAULT 0,
            PID_2 INT UNSIGNED NOT NULL DEFAULT 0,
            SORT_TYPE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_USER_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            NAME VARCHAR(255) NOT NULL DEFAULT '',
            TYPE TINYINT(1) UNSIGNED NOT NULL DEFAULT 2,
            INVENTORY_REQ TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            REAL_PRICE DOUBLE UNSIGNED NOT NULL DEFAULT 0,
            DT_REPRICING INT UNSIGNED NOT NULL DEFAULT 0,
            DESCR_REPRICING MEDIUMTEXT NULL,
            REPRICING_AMORT INT UNSIGNED NOT NULL DEFAULT 0,
            ID_AMT_OUT INT UNSIGNED NOT NULL DEFAULT 0,
            PRIMARY KEY (ID),
            KEY idx_funds_pid (PID)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );

    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_fund_movements (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            ID_FUND INT UNSIGNED NOT NULL DEFAULT 0,
            ID_TYPE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_FUND_TYPE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_USER_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_USER_UPDATE INT UNSIGNED NOT NULL DEFAULT 0,
            DIRECTION TINYINT(1) NOT NULL DEFAULT 0,
            SUMM DOUBLE UNSIGNED NOT NULL DEFAULT 0,
            SUMM_OUT_CAP DOUBLE UNSIGNED NOT NULL DEFAULT 0,
            SUMM_OUT_FUND DOUBLE UNSIGNED NOT NULL DEFAULT 0,
            SUMM_OUT_INFL DOUBLE UNSIGNED NOT NULL DEFAULT 0,
            SUMM_OUT_DESTROY DOUBLE UNSIGNED NOT NULL DEFAULT 0,
            NAME VARCHAR(255) NOT NULL DEFAULT '',
            DESCR MEDIUMTEXT NULL,
            DT_AMORT_START INT UNSIGNED NOT NULL DEFAULT 0,
            DT_AMORT_END INT UNSIGNED NOT NULL DEFAULT 0,
            DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_UPDATE INT UNSIGNED NOT NULL DEFAULT 0,
            AMORT_MONTHS INT NOT NULL DEFAULT 0,
            VALUE INT NOT NULL DEFAULT 0,
            PRIMARY KEY (ID),
            KEY idx_fm_fund (ID_FUND),
            KEY idx_fm_type (ID_TYPE)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );
};
