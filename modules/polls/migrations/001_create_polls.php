<?php
declare(strict_types=1);

/**
 * Poll definition tree (poll / question / answer). Shared with legacy oper.
 */
return static function (PDO $pdo): void {
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_polls (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            PID INT UNSIGNED NOT NULL DEFAULT 0,
            EL_TYPE TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            NAME VARCHAR(255) NOT NULL DEFAULT '',
            DT INT UNSIGNED NOT NULL DEFAULT 0,
            DESCR_ADMIN TEXT NOT NULL,
            DESCR_SITE TEXT NOT NULL,
            RESP_GROUPS TEXT NOT NULL,
            BONUS_DEFAULT INT UNSIGNED NOT NULL DEFAULT 0,
            BONUS_AUTO TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            ENABLED TINYINT(1) UNSIGNED NOT NULL DEFAULT 1,
            REQ_TEXT_LEN TINYINT UNSIGNED NOT NULL DEFAULT 0,
            NUM TINYINT NOT NULL DEFAULT 0,
            QTY TINYINT UNSIGNED NOT NULL DEFAULT 0,
            STORE_TO_USER TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            MULTY_OPTS TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            TYPES TEXT NOT NULL,
            PROCS TEXT NOT NULL,
            STATS_USERS_AMOUNT INT UNSIGNED NOT NULL DEFAULT 0,
            NEXT_QID INT UNSIGNED NOT NULL DEFAULT 0,
            WHO_CAN_PASS TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            SHOW2USER TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            ADD2DTNEXT INT UNSIGNED NOT NULL DEFAULT 0,
            STATUS_ON_SEL INT UNSIGNED NOT NULL DEFAULT 0,
            SHOW_IN_TRAY TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            TRAY_CODE VARCHAR(10) NOT NULL DEFAULT '',
            STATUSES TEXT NOT NULL,
            NEGATIVE TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            MULTY_ANSWER TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            ANS_END_POLL TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            AFTER_EVENT TINYINT UNSIGNED NOT NULL DEFAULT 0,
            AFTER_EVENT_STOP_REW TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            AFTER_EVENT_TIME INT UNSIGNED NOT NULL DEFAULT 0,
            AFTER_EVENT_EXPIRE_TIME INT UNSIGNED NOT NULL DEFAULT 0,
            SHOW_HISTORY TINYINT UNSIGNED NOT NULL DEFAULT 0,
            NOT_REPASS TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            IS_SPECIAL TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            IS_SPECIAL_FRIEND TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            IS_RESULT TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            NOTICE_SMS TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            NOTICE_EMAIL TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            NOTICE_SMS_TPL_ID INT UNSIGNED NOT NULL DEFAULT 0,
            NOTICE_EMAIL_TPL_ID INT UNSIGNED NOT NULL DEFAULT 0,
            PRIMARY KEY (ID),
            KEY idx_polls_pid (PID),
            KEY idx_polls_el_type (EL_TYPE),
            KEY idx_polls_enabled (ENABLED)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );
};
