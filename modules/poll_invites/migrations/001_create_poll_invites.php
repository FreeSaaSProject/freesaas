<?php
declare(strict_types=1);

/**
 * Poll invite instances + answers (DATA_OPTS). Shared with legacy oper.
 */
return static function (PDO $pdo): void {
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_poll_invites (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_AVAIL INT UNSIGNED NOT NULL DEFAULT 0,
            DT_EXPIRE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_STARTED INT UNSIGNED NOT NULL DEFAULT 0,
            DT_COMPLETED INT UNSIGNED NOT NULL DEFAULT 0,
            DT_RECOMPLETED INT UNSIGNED NOT NULL DEFAULT 0,
            ID_OPERATOR_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_OPERATOR_LINKED INT UNSIGNED NOT NULL DEFAULT 0,
            ID_OPERATOR_UPDATE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_OPERATOR_UPDATE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_USER INT UNSIGNED NOT NULL DEFAULT 0,
            ID_EVENT INT UNSIGNED NOT NULL DEFAULT 0,
            ID_PROC INT UNSIGNED NOT NULL DEFAULT 0,
            ID_POLL INT UNSIGNED NOT NULL DEFAULT 0,
            TEXT_ADMIN_TO_USER TEXT NOT NULL,
            BONUS_AUTO TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            BONUS_VALUE INT UNSIGNED NOT NULL DEFAULT 0,
            BONUS_GIVEN INT UNSIGNED NOT NULL DEFAULT 0,
            LOG TEXT NOT NULL,
            DT_NEXTCALL INT UNSIGNED NOT NULL DEFAULT 0,
            STATUS TINYINT UNSIGNED NOT NULL DEFAULT 0,
            DATA_OPTS TEXT NOT NULL,
            DATA_TEXT TEXT NOT NULL,
            RESP_USERS TEXT NOT NULL,
            RESP_USERS_VIEWED TEXT NOT NULL,
            CODE VARCHAR(32) NOT NULL DEFAULT '',
            CODE_FRIEND VARCHAR(32) NOT NULL DEFAULT '',
            USERS_VIEWED TEXT NOT NULL,
            IS_SPECIAL TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            IS_SPECIAL_FRIEND TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            IS_RESULT TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            SIGN_REQ TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            ID_SUPERVISOR_SIGNED INT UNSIGNED NOT NULL DEFAULT 0,
            DT_SUPERVISOR_SIGNED INT UNSIGNED NOT NULL DEFAULT 0,
            ID_ORDER_NEW INT UNSIGNED NOT NULL DEFAULT 0,
            ID_ORDER_FRIEND_NEW INT UNSIGNED NOT NULL DEFAULT 0,
            ID_GBOOK INT UNSIGNED NOT NULL DEFAULT 0,
            PRIMARY KEY (ID),
            KEY idx_poll_invites_user (ID_USER),
            KEY idx_poll_invites_dt_create (DT_CREATE),
            KEY idx_poll_invites_poll (ID_POLL),
            KEY idx_poll_invites_code (CODE),
            KEY idx_poll_invites_completed (DT_COMPLETED)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );
};
