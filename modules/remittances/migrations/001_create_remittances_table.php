return static function (PDO $pdo): void {
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_remittance_agreements (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            NAME VARCHAR(255) NOT NULL DEFAULT '',
            ENABLED TINYINT(1) UNSIGNED NOT NULL DEFAULT 1,
            ID_SUPPLIER INT UNSIGNED NOT NULL DEFAULT 0,
            ID_ACCOUNT INT UNSIGNED NOT NULL DEFAULT 0,
            ID_TYPE INT UNSIGNED NOT NULL DEFAULT 0,
            FEE_PERCENT DECIMAL(8,4) NOT NULL DEFAULT 2.0000,
            FEE_POSTING VARCHAR(32) NOT NULL DEFAULT 'none',
            FEE_MOVE_TYPE_ID INT UNSIGNED NOT NULL DEFAULT 0,
            FEE_ACCOUNT_ID INT UNSIGNED NOT NULL DEFAULT 0,
            PARSER_PRESET VARCHAR(64) NOT NULL DEFAULT '',
            PATTERN_PERIOD_FROM VARCHAR(512) NOT NULL DEFAULT '',
            PATTERN_PERIOD_TO VARCHAR(512) NOT NULL DEFAULT '',
            PATTERN_GROSS VARCHAR(512) NOT NULL DEFAULT '',
            PATTERN_FEE VARCHAR(512) NOT NULL DEFAULT '',
            EXPECTED_CHANNELS VARCHAR(255) NOT NULL DEFAULT 'spa_ops',
            AUTO_SET_SUPPLIER TINYINT(1) UNSIGNED NOT NULL DEFAULT 1,
            DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_UPDATE INT UNSIGNED NOT NULL DEFAULT 0,
            PRIMARY KEY (ID),
            KEY idx_supplier (ID_SUPPLIER),
            KEY idx_enabled (ENABLED)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );

    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_remittance_batches (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            ID_AGREEMENT INT UNSIGNED NOT NULL DEFAULT 0,
            ID_MOVE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_FEE_MOVE INT UNSIGNED NOT NULL DEFAULT 0,
            PERIOD_FROM DATE NULL DEFAULT NULL,
            PERIOD_TO DATE NULL DEFAULT NULL,
            GROSS DECIMAL(14,2) NOT NULL DEFAULT 0,
            FEE DECIMAL(14,2) NOT NULL DEFAULT 0,
            NET DECIMAL(14,2) NOT NULL DEFAULT 0,
            EXPECTED DECIMAL(14,2) NOT NULL DEFAULT 0,
            DELTA_GROSS DECIMAL(14,2) NOT NULL DEFAULT 0,
            DELTA_NET DECIMAL(14,2) NOT NULL DEFAULT 0,
            STATUS VARCHAR(32) NOT NULL DEFAULT 'unparsed',
            PARSE_ERROR VARCHAR(512) NOT NULL DEFAULT '',
            IGNORED TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_UPDATE INT UNSIGNED NOT NULL DEFAULT 0,
            PRIMARY KEY (ID),
            UNIQUE KEY uq_move (ID_MOVE),
            KEY idx_agreement (ID_AGREEMENT),
            KEY idx_status (STATUS),
            KEY idx_period (PERIOD_FROM, PERIOD_TO)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );
};
