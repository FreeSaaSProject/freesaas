<?php
declare(strict_types=1);

/**
 * Procedure types, journal, and restores.
 * Shared with legacy oper — keep uppercase column names.
 */
return static function (PDO $pdo): void {
    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_procedure_types (
            ID INT NOT NULL AUTO_INCREMENT,
            TYPE VARCHAR(255) NOT NULL DEFAULT '',
            SUBTYPE INT UNSIGNED NOT NULL DEFAULT 0,
            DESCR VARCHAR(255) NOT NULL DEFAULT '',
            BONUS_PROCENT FLOAT NOT NULL DEFAULT 0,
            MULTIWORK TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            PHOTO_REQ TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            IS_MEDICAL TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            PARALLELS INT UNSIGNED NOT NULL DEFAULT 0,
            BONUS_PROCENT_OUT FLOAT UNSIGNED NOT NULL DEFAULT 0,
            SITE_AMO_SHOW TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            CONS_REQ_AMO INT UNSIGNED NOT NULL DEFAULT 0,
            PRIMARY KEY (ID)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );

    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_procedures (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            DTCREATE INT UNSIGNED NOT NULL DEFAULT 0,
            DTSTART INT UNSIGNED NOT NULL DEFAULT 0,
            DTEND INT UNSIGNED NOT NULL DEFAULT 0,
            DTEND_PLAN INT UNSIGNED NOT NULL DEFAULT 0,
            ID_OPERATOR INT UNSIGNED NOT NULL DEFAULT 0,
            ID_ADMIN INT UNSIGNED NOT NULL DEFAULT 0,
            ID_GOOD INT UNSIGNED NOT NULL DEFAULT 0,
            ID_TABLE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_USER INT UNSIGNED NOT NULL DEFAULT 0,
            ID_TERMINAL INT UNSIGNED NOT NULL DEFAULT 0,
            TYPE INT UNSIGNED NOT NULL DEFAULT 0,
            SUMM INT UNSIGNED NOT NULL DEFAULT 0,
            SUMM_DEFAULT INT UNSIGNED NOT NULL DEFAULT 0,
            NOTICE VARCHAR(255) NOT NULL DEFAULT '',
            ENABLED TINYINT(1) UNSIGNED NOT NULL DEFAULT 1,
            TOKEN VARCHAR(32) NOT NULL DEFAULT '',
            ID_EVENT_PARENT INT UNSIGNED NOT NULL DEFAULT 0,
            `1C_ID` VARCHAR(40) NOT NULL DEFAULT '',
            `1C_BRACELET` VARCHAR(32) NOT NULL DEFAULT '',
            RESTORED TINYINT(1) UNSIGNED NOT NULL DEFAULT 0,
            PRIMARY KEY (ID),
            KEY DTSTART (DTSTART),
            KEY DTEND (DTEND)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );

    $pdo->exec(
        "CREATE TABLE IF NOT EXISTS base_procedure_restores (
            ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
            DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            DT_REVIEW INT UNSIGNED NOT NULL DEFAULT 0,
            ID_PROCEDURE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_ADMIN_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
            ID_OPERATOR_PAID INT UNSIGNED NOT NULL DEFAULT 0,
            ID_OPERATOR_REVIEWED INT UNSIGNED NOT NULL DEFAULT 0,
            REASON VARCHAR(255) NOT NULL DEFAULT '',
            SUMM FLOAT NOT NULL DEFAULT 0,
            PRIMARY KEY (ID)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"
    );
};
