<?php
declare(strict_types=1);

return static function (PDO $pdo): void {
    $pdo->exec("CREATE TABLE IF NOT EXISTS base_course_programs (
        ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
        NAME VARCHAR(255) NOT NULL DEFAULT '',
        DESCR TEXT NULL,
        AUDIENCE VARCHAR(16) NOT NULL DEFAULT 'clients',
        PRODUCT_ID INT UNSIGNED NOT NULL DEFAULT 0,
        ACCESS_DAYS INT UNSIGNED NOT NULL DEFAULT 0,
        ENABLED TINYINT(1) UNSIGNED NOT NULL DEFAULT 1,
        DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
        DT_UPDATE INT UNSIGNED NOT NULL DEFAULT 0,
        PRIMARY KEY (ID),
        KEY idx_course_prog_product (PRODUCT_ID),
        KEY idx_course_prog_aud (AUDIENCE, ENABLED)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");

    $pdo->exec("CREATE TABLE IF NOT EXISTS base_course_modules (
        ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
        PROGRAM_ID INT UNSIGNED NOT NULL DEFAULT 0,
        NAME VARCHAR(255) NOT NULL DEFAULT '',
        SORT INT NOT NULL DEFAULT 0,
        PRIMARY KEY (ID),
        KEY idx_course_mod_prog (PROGRAM_ID, SORT)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");

    $pdo->exec("CREATE TABLE IF NOT EXISTS base_course_lessons (
        ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
        PROGRAM_ID INT UNSIGNED NOT NULL DEFAULT 0,
        MODULE_ID INT UNSIGNED NOT NULL DEFAULT 0,
        NAME VARCHAR(255) NOT NULL DEFAULT '',
        BODY MEDIUMTEXT NULL,
        SORT INT NOT NULL DEFAULT 0,
        DRIP_DAYS INT UNSIGNED NOT NULL DEFAULT 0,
        ENABLED TINYINT(1) UNSIGNED NOT NULL DEFAULT 1,
        PRIMARY KEY (ID),
        KEY idx_course_les_prog (PROGRAM_ID, SORT),
        KEY idx_course_les_mod (MODULE_ID)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");

    $pdo->exec("CREATE TABLE IF NOT EXISTS base_course_assets (
        ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
        LESSON_ID INT UNSIGNED NOT NULL DEFAULT 0,
        KIND VARCHAR(32) NOT NULL DEFAULT 'file',
        TITLE VARCHAR(255) NOT NULL DEFAULT '',
        STORAGE_PATH VARCHAR(512) NOT NULL DEFAULT '',
        MIME VARCHAR(128) NOT NULL DEFAULT '',
        BYTES INT UNSIGNED NOT NULL DEFAULT 0,
        PRIMARY KEY (ID),
        KEY idx_course_asset_lesson (LESSON_ID)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");

    $pdo->exec("CREATE TABLE IF NOT EXISTS base_course_enrollments (
        ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
        PROGRAM_ID INT UNSIGNED NOT NULL DEFAULT 0,
        SUBJECT_TYPE VARCHAR(16) NOT NULL DEFAULT 'client',
        SUBJECT_ID INT UNSIGNED NOT NULL DEFAULT 0,
        ACCESS_FROM INT UNSIGNED NOT NULL DEFAULT 0,
        ACCESS_UNTIL INT UNSIGNED NOT NULL DEFAULT 0,
        SOURCE VARCHAR(32) NOT NULL DEFAULT 'manual',
        ORDER_ID INT UNSIGNED NOT NULL DEFAULT 0,
        DT_CREATE INT UNSIGNED NOT NULL DEFAULT 0,
        PRIMARY KEY (ID),
        KEY idx_course_enr_subj (SUBJECT_TYPE, SUBJECT_ID),
        KEY idx_course_enr_prog (PROGRAM_ID),
        KEY idx_course_enr_order (ORDER_ID)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");

    $pdo->exec("CREATE TABLE IF NOT EXISTS base_course_progress (
        ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
        ENROLLMENT_ID INT UNSIGNED NOT NULL DEFAULT 0,
        LESSON_ID INT UNSIGNED NOT NULL DEFAULT 0,
        DT_DONE INT UNSIGNED NOT NULL DEFAULT 0,
        PRIMARY KEY (ID),
        UNIQUE KEY uq_course_progress (ENROLLMENT_ID, LESSON_ID)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");

    $pdo->exec("CREATE TABLE IF NOT EXISTS base_course_media_hits (
        ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
        ASSET_ID INT UNSIGNED NOT NULL DEFAULT 0,
        SUBJECT_TYPE VARCHAR(16) NOT NULL DEFAULT '',
        SUBJECT_ID INT UNSIGNED NOT NULL DEFAULT 0,
        IP VARCHAR(64) NOT NULL DEFAULT '',
        DT_HIT INT UNSIGNED NOT NULL DEFAULT 0,
        PRIMARY KEY (ID),
        KEY idx_course_hit_asset (ASSET_ID, DT_HIT)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
};
